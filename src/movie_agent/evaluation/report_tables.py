"""Report tables and figures, generated only from saved results (design §9.7, §10).

Writes `eval/results/report_tables.md` and at most three figures in `eval/results/figures/`.
For each kind of run the most recent results directory is used; its name is printed next to
every table so each number can be traced back to a run.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib
import pandas as pd
import yaml

from movie_agent.config import Config
from movie_agent.evaluation.results import fmt_ci
from movie_agent.evaluation.scenarios import RUBRIC_CRITERIA

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402  (backend must be set first)

KINDS = ("offline_test", "offline_val", "search", "agent", "honesty")


def latest_run(results_dir: Path, kind: str) -> Path | None:
    """Most recent `<date>_<kind>[_n]` directory that has a metrics.json."""
    runs = [
        p
        for p in results_dir.glob(f"*_{kind}*")
        if (p / "metrics.json").exists()
        and p.name.split("_", 1)[1].rstrip("0123456789").rstrip("_") == kind
    ]
    return max(runs, key=lambda p: (p / "metrics.json").stat().st_mtime, default=None)


def run_report_tables(cfg: Config) -> Path:
    results = cfg.paths.results_dir
    runs = {k: latest_run(results, k) for k in KINDS}
    lines = [
        "# Report tables",
        "",
        "Generated by `movie-agent report-tables`; do not edit by hand.",
        "",
    ]
    offline = runs["offline_test"] or runs["offline_val"]
    if offline:
        m = _load(offline)
        lines += _offline_tables(m, offline.name)
        _figures(m, results / "figures")
    if runs["search"]:
        lines += _search_table(_load(runs["search"]), runs["search"].name)
    if runs["agent"]:
        lines += _agent_table(_load(runs["agent"]), runs["agent"])
        lines += _agent_runs_table(results)
    if runs["honesty"]:
        lines += _honesty_table(_load(runs["honesty"]), runs["honesty"].name)
    out = results / "report_tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip() + "\n")
    return out


def _load(run: Path) -> dict:
    return json.loads((run / "metrics.json").read_text())


def _offline_tables(m: dict, run: str) -> list[str]:
    lines = [
        f"## Offline ranking ({m['split']}, K = {m['k']}, {m['n_users']} users) — `{run}`",
        "",
        "| System | Recall@K | NDCG@K | Tail recall | Coverage | Pop. ratio |",
        "|---|---|---|---|---|---|",
    ]
    for name, s in m["systems"].items():
        lines.append(
            f"| {name} | {fmt_ci(s['recall'])} | {fmt_ci(s['ndcg'])} | "
            f"{fmt_ci(s['tail_recall'])} | {s['coverage']:.3f} | {s['pop_ratio']:.2f} |"
        )
    lines += [
        "",
        "| Comparison | Metric | Mean difference [95% CI] | Significant |",
        "|---|---|---|---|",
    ]
    for comp, metrics in m["paired"].items():
        lines += [
            f"| {comp} | {k} | {fmt_ci(v)} | {'yes' if v['significant'] else 'no'} |"
            for k, v in metrics.items()
        ]
    return [*lines, ""]


def _search_table(m: dict, run: str) -> list[str]:
    lines = [
        f"## Content search ({m['n_queries']} queries) — `{run}`",
        "",
        "| Variant | P@5 | Mean grade (0–2) | Mean Bayesian avg | Share < 5 ratings |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {n} | {fmt_ci(v['p_at_k'], 2)} | {fmt_ci(v['mean_grade'], 2)} | "
        f"{v['mean_bayes_avg']:.2f} | {v['share_under_5_ratings']:.2f} |"
        for n, v in m["variants"].items()
    ]
    return [*lines, ""]


def _agent_runs_table(results: Path) -> list[str]:
    """Every saved agent run side by side: prompt changes and run-to-run variance."""
    runs = sorted(
        (p for p in results.glob("*_agent*") if (p / "metrics.json").exists()),
        key=lambda p: (p / "metrics.json").stat().st_mtime,
    )
    keys = ["verifier_first_pass_rate", "fallback_rate", "state_persistence", "scenario_success"]
    lines = [
        "### All agent runs",
        "",
        "| Run | Prompt | Commit | " + " | ".join(keys) + " |",
        "|---|---|---|" + "---|" * len(keys),
    ]
    for run in runs:
        m = _load(run)
        cfg = yaml.safe_load((run / "config.yaml").read_text())
        values = " | ".join(f"{m[k]:.2f}" if isinstance(m.get(k), float) else "-" for k in keys)
        lines.append(
            f"| `{run.name}` | {cfg['agent']['prompt_version']} | "
            f"{m['meta']['git_commit']} | {values} |"
        )
    return [*lines, ""]


def _agent_table(m: dict, run: Path) -> list[str]:
    keys = [
        "scenario_success",
        "tool_chain_accuracy",
        "verifier_first_pass_rate",
        "fallback_rate",
        "constraint_satisfaction",
        "state_persistence",
        "mean_tool_calls",
        "mean_tokens",
        "p50_latency_ms",
        "p95_latency_ms",
    ]
    lines = [
        f"## Agent scenarios ({m['n_scenarios']} scenarios, {m['n_turns']} turns) — `{run.name}`",
        "",
        "| Metric | Value |",
        "|---|---|",
    ]
    lines += [f"| {k} | {m[k]:.3f} |" for k in keys if isinstance(m.get(k), float)]
    sheet = run / "rubric_sheet.csv"
    if sheet.exists():
        grades = pd.read_csv(sheet)[list(RUBRIC_CRITERIA)].apply(pd.to_numeric, errors="coerce")
        if grades.notna().any().any():
            lines += ["", "| Rubric criterion (0–2) | Mean | Graded turns |", "|---|---|---|"]
            lines += [
                f"| {c} | {grades[c].mean():.2f} | {int(grades[c].notna().sum())} |"
                for c in RUBRIC_CRITERIA
            ]
    return [*lines, ""]


def _honesty_table(m: dict, run: str) -> list[str]:
    f = m["fidelity"]
    lines = [
        f"## Honesty tests — `{run}`",
        "",
        "| Test | Result |",
        "|---|---|",
        f"| Fidelity: top driver removed → recommendation drops | "
        f"{fmt_ci(f['driver_faithful'], 2)} (n = {f['n_with_history_driver']}) |",
        f"| Control: random history movie removed | {fmt_ci(f['control_faithful'], 2)} |",
    ]
    if "perturbation" in m:
        p, a = m["perturbation"], m["llm_attribution"]
        lines += [
            f"| Perturbation: pairs where the data flipped | "
            f"{p['data_direction_flipped']} of {p['n_pairs']} |",
            f"| LLM answer names the engine's top driver | {a['mentions_driver_rate']} "
            f"(n = {a['n']}) |",
        ]
    return [*lines, ""]


def _figures(m: dict, out: Path) -> None:
    """Three figures: accuracy by system, NDCG by history tercile, popularity of recommendations."""
    out.mkdir(parents=True, exist_ok=True)
    systems = list(m["systems"])
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.5))
    for ax, metric in zip(axes, ("recall", "ndcg"), strict=True):
        values = [m["systems"][s][metric] for s in systems]
        ax.bar(
            systems,
            [v["mean"] for v in values],
            yerr=[[v["mean"] - v["lo"] for v in values], [v["hi"] - v["mean"] for v in values]],
            capsize=3,
            color="#4C78A8",
        )
        ax.set_title(f"{metric.upper()}@{m['k']} ({m['split']}, 95% CI)")
        ax.tick_params(axis="x", rotation=30)
    fig.tight_layout()
    fig.savefig(out / "accuracy_by_system.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.5))
    width = 0.8 / len(systems)
    for i, s in enumerate(systems):
        seg = m["systems"][s]["segments"]
        tiers = [t for t in ("small", "medium", "large") if t in seg]
        ax.bar(
            [j + i * width for j in range(len(tiers))],
            [seg[t]["ndcg"]["mean"] for t in tiers],
            width=width,
            label=s,
        )
    ax.set_xticks([j + 0.4 - width / 2 for j in range(3)], ["small", "medium", "large"])
    ax.set_title("NDCG by train-history tercile")
    ax.legend(fontsize=7, ncol=3)
    fig.tight_layout()
    fig.savefig(out / "ndcg_by_history_tercile.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.5))
    ax.bar(systems, [m["systems"][s]["pop_ratio"] for s in systems], color="#F58518")
    ax.axhline(1.0, color="grey", linestyle="--", linewidth=1)
    ax.set_title("Mean popularity of recommendations / of the user's history")
    ax.tick_params(axis="x", rotation=30)
    fig.tight_layout()
    fig.savefig(out / "popularity_ratio.png", dpi=150)
    plt.close(fig)
