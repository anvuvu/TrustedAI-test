"""Report tables and figures, generated only from saved results (design §9.7, §10).

Writes `eval/results/report_tables.md` and at most three figures in `eval/results/figures/`.
For each kind of run the most recent results directory is used (for the LLM runs, the most
recent one made with the configured model); its name is printed next to every table so each
number can be traced back to a run.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd
import yaml

from movie_agent.config import PROJECT_ROOT, Config
from movie_agent.evaluation.results import fmt_ci, paired_bootstrap
from movie_agent.evaluation.scenarios import RUBRIC_CRITERIA

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402  (backend must be set first)

KINDS = ("offline_test", "offline_val", "search", "agent", "honesty")
LLM_KINDS = ("agent", "honesty")
GRADING_DIR = PROJECT_ROOT / "eval" / "grading"
# The report and its Vietnamese translation carry the same generated tables.
REPORTS = (PROJECT_ROOT / "REPORT.md", PROJECT_ROOT / "REPORT.vi.md")


def latest_run(results_dir: Path, kind: str, model: str | None = None) -> Path | None:
    """Most recent `<date>_<kind>[_n]` directory that has a metrics.json and, if `model` is
    given, whose config snapshot used that LLM."""
    runs = [
        p
        for p in results_dir.glob(f"*_{kind}*")
        if (p / "metrics.json").exists()
        and p.name.split("_", 1)[1].rstrip("0123456789").rstrip("_") == kind
        and (model is None or run_model(p) == model)
    ]
    return max(runs, key=lambda p: (p / "metrics.json").stat().st_mtime, default=None)


def run_model(run: Path) -> str | None:
    """The LLM recorded in a run's config snapshot, or None if there is no snapshot."""
    snapshot = run / "config.yaml"
    if not snapshot.exists():
        return None
    return (yaml.safe_load(snapshot.read_text()).get("agent") or {}).get("model")


def run_report_tables(cfg: Config, reports: tuple[Path, ...] = REPORTS) -> Path:
    """Write report_tables.md and the figures, and refresh the tables inside the reports.

    In each report (REPORT.md and its translation REPORT.vi.md), the text between
    `<!-- table:NAME -->` and `<!-- /table:NAME -->` is replaced by the generated section NAME
    (offline, search, agent, agent_runs, honesty, model_swap), so the report's tables always
    come from saved results. The agent and honesty tables use runs made with the configured
    model; `agent_runs` lists every run with its model.
    """
    results = cfg.paths.results_dir
    model = cfg.agent.model
    runs = {k: latest_run(results, k, model if k in LLM_KINDS else None) for k in KINDS}
    agent = latest_graded_agent_run(results, model) or runs["agent"]
    sections: dict[str, list[str]] = {}
    offline = runs["offline_test"] or runs["offline_val"]
    if offline:
        m = _load(offline)
        sections["offline"] = _offline_tables(m, offline.name)
        sections["segments"] = _segments_table(m, offline.name)
        _figures(m, results / "figures")
    if runs["search"]:
        sections["search"] = _search_table(_load(runs["search"]), runs["search"].name)
        grades = PROJECT_ROOT / "eval" / "grading" / "search_grades_with_rationale.csv"
        if grades.exists():
            sections["search_failures"] = _search_failures_table(grades)
    if agent:
        sections["agent"] = _agent_table(_load(agent), agent)
        sections["agent_runs"] = _agent_runs_table(results)
    if runs["honesty"]:
        sections["honesty"] = _honesty_table(_load(runs["honesty"]), runs["honesty"])
    swap = _model_swap_table(cfg, GRADING_DIR, results)
    if swap:
        sections["model_swap"] = swap
    lines = [
        "# Report tables",
        "",
        "Generated by `movie-agent report-tables`; do not edit by hand.",
        "",
    ]
    for section in sections.values():
        lines += section
    out = results / "report_tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip() + "\n")
    for report in reports:
        if report.exists():
            report.write_text(refresh_report(report.read_text(), sections))
    return out


def latest_graded_agent_run(results: Path, model: str | None = None) -> Path | None:
    """Most recent agent run whose rubric sheet has grades (made with `model`, if given)."""
    graded = [
        p
        for p in results.glob("*_agent*")
        if (p / "rubric_sheet.csv").exists()
        and _rubric_means(p)[0] != "-"
        and (model is None or run_model(p) == model)
    ]
    return max(graded, key=lambda p: (p / "metrics.json").stat().st_mtime, default=None)


_MARKER = re.compile(r"(<!-- table:(\w+) -->)(.*?)(<!-- /table:\2 -->)", re.DOTALL)


def refresh_report(text: str, sections: dict[str, list[str]]) -> str:
    """Replace each marked table block with its generated section (headings become captions)."""

    def body(match: re.Match[str]) -> str:
        name = match.group(2)
        if name not in sections:
            return match.group(0)
        rows = []
        for line in sections[name]:
            if line.startswith("#"):
                rows.append(f"*Source: {line.lstrip('# ').strip()}*")
            else:
                rows.append(line)
        return f"{match.group(1)}\n" + "\n".join(rows).strip() + f"\n{match.group(4)}"

    return _MARKER.sub(body, text)


def _load(run: Path) -> dict:
    return json.loads((run / "metrics.json").read_text())


def _offline_tables(m: dict, run: str) -> list[str]:
    lines = [
        f"## Offline ranking ({m['split']}, K = {m['k']}, {m['n_users']} users) — `{run}`",
        "",
        "| System | Recall@K | NDCG@K | Tail recall | Coverage | Pop. ratio |",
        "|---|---|---|---|---|---|",
    ]
    for name, s in m["systems"].items():
        lines.append(
            f"| {name} | {fmt_ci(s['recall'])} | {fmt_ci(s['ndcg'])} | "
            f"{fmt_ci(s['tail_recall'])} | {s['coverage']:.3f} | {s['pop_ratio']:.2f} |"
        )
    lines += [
        "",
        "| Comparison | Metric | Mean difference [95% CI] | Significant |",
        "|---|---|---|---|",
    ]
    for comp, metrics in m["paired"].items():
        lines += [
            f"| {comp} | {k} | {fmt_ci(v)} | {'yes' if v['significant'] else 'no'} |"
            for k, v in metrics.items()
        ]
    return [*lines, ""]


def _segments_table(m: dict, run: str) -> list[str]:
    cuts = ", ".join(f"{c:.0f}" for c in m["history_terciles"])
    lines = [
        f"### NDCG@{m['k']} by train-history tercile (cut points {cuts} ratings) — `{run}`",
        "",
        "| System | small | medium | large |",
        "|---|---|---|---|",
    ]
    for name, s in m["systems"].items():
        seg = s["segments"]
        cells = [fmt_ci(seg[t]["ndcg"]) if t in seg else "-" for t in ("small", "medium", "large")]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return [*lines, ""]


def _search_failures_table(path: Path) -> list[str]:
    """Mean grade and failure types per query, from the graded search sheet."""
    g = pd.read_csv(path)
    types = sorted(g["failure_type"].dropna().unique())
    lines = [
        "### Search grades by query (LLM-graded) — `eval/grading/search_grades_with_rationale.csv`",
        "",
        "| Query | Pairs | Mean grade | " + " | ".join(types) + " |",
        "|---|---|---|" + "---|" * len(types),
    ]
    for query, q in g.groupby("query_id"):
        counts = [str(int((q["failure_type"] == t).sum())) for t in types]
        lines.append(
            f"| {query} | {len(q)} | {q['grade'].mean():.2f} | " + " | ".join(counts) + " |"
        )
    totals = [str(int((g["failure_type"] == t).sum())) for t in types]
    lines.append(f"| all | {len(g)} | {g['grade'].mean():.2f} | " + " | ".join(totals) + " |")
    return [*lines, ""]


def _search_table(m: dict, run: str) -> list[str]:
    lines = [
        f"## Content search ({m['n_queries']} queries) — `{run}`",
        "",
        "| Variant | P@5 | Mean grade (0–2) | Mean Bayesian avg | Share < 5 ratings |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {n} | {fmt_ci(v['p_at_k'], 2)} | {fmt_ci(v['mean_grade'], 2)} | "
        f"{v['mean_bayes_avg']:.2f} | {v['share_under_5_ratings']:.2f} |"
        for n, v in m["variants"].items()
    ]
    return [*lines, ""]


def _agent_runs_table(results: Path) -> list[str]:
    """Every saved agent run side by side: model and prompt changes, run-to-run variance."""
    runs = sorted(
        (p for p in results.glob("*_agent*") if (p / "metrics.json").exists()),
        key=lambda p: (p / "metrics.json").stat().st_mtime,
    )
    keys = ["verifier_first_pass_rate", "fallback_rate", "state_persistence", "scenario_success"]
    header = keys + [f"rubric {c}" for c in RUBRIC_CRITERIA]
    lines = [
        "### All agent runs",
        "",
        "Rubric columns are means (0–2) where the run was graded (by an LLM grader, see notes).",
        "",
        "| Run | Model | Prompt | Commit | " + " | ".join(header) + " |",
        "|---|---|---|---|" + "---|" * len(header),
    ]
    for run in runs:
        m = _load(run)
        cfg = yaml.safe_load((run / "config.yaml").read_text())
        values = [f"{m[k]:.2f}" if isinstance(m.get(k), float) else "-" for k in keys]
        values += _rubric_means(run)
        lines.append(
            f"| `{run.name}` | {cfg['agent']['model']} | {cfg['agent']['prompt_version']} | "
            f"{m['meta']['git_commit']} | {' | '.join(values)} |"
        )
    return [*lines, ""]


def _rubric_means(run: Path) -> list[str]:
    """Mean grade per rubric criterion for a run, or "-" if its sheet is not graded."""
    sheet = run / "rubric_sheet.csv"
    if not sheet.exists():
        return ["-"] * len(RUBRIC_CRITERIA)
    grades = pd.read_csv(sheet)[list(RUBRIC_CRITERIA)].apply(pd.to_numeric, errors="coerce")
    return [f"{grades[c].mean():.2f}" if grades[c].notna().any() else "-" for c in RUBRIC_CRITERIA]


def _agent_table(m: dict, run: Path) -> list[str]:
    keys = [
        "scenario_success",
        "tool_chain_accuracy",
        "verifier_first_pass_rate",
        "fallback_rate",
        "constraint_satisfaction",
        "state_persistence",
        "mean_tool_calls",
        "mean_tokens",
        "p50_latency_ms",
        "p95_latency_ms",
    ]
    lines = [
        f"## Agent scenarios ({m['n_scenarios']} scenarios, {m['n_turns']} turns) — `{run.name}`",
        "",
        "| Metric | Value |",
        "|---|---|",
    ]
    lines += [f"| {k} | {m[k]:.3f} |" for k in keys if isinstance(m.get(k), float)]
    sheet = run / "rubric_sheet.csv"
    if sheet.exists():
        grades = pd.read_csv(sheet)[list(RUBRIC_CRITERIA)].apply(pd.to_numeric, errors="coerce")
        if grades.notna().any().any():
            lines += ["", "| Rubric criterion (0–2) | Mean | Graded turns |", "|---|---|---|"]
            lines += [
                f"| {c} | {grades[c].mean():.2f} | {int(grades[c].notna().sum())} |"
                for c in RUBRIC_CRITERIA
            ]
    return [*lines, ""]


def _honesty_table(m: dict, run: Path) -> list[str]:
    f = m["fidelity"]
    lines = [
        f"## Honesty tests — `{run.name}`",
        "",
        "| Test | Result |",
        "|---|---|",
        f"| Fidelity: top driver removed → recommendation drops | "
        f"{fmt_ci(f['driver_faithful'], 2)} (n = {f['n_with_history_driver']}) |",
        f"| Control: random history movie removed | {fmt_ci(f['control_faithful'], 2)} |",
    ]
    if "perturbation" in m:
        p, a = m["perturbation"], m["llm_attribution"]
        lines += [
            f"| Perturbation: pairs where the data flipped | "
            f"{p['data_direction_flipped']} of {p['n_pairs']} |",
            f"| LLM answer names the engine's top driver | {a['mentions_driver_rate']} "
            f"(n = {a['n']}) |",
        ]
    lines += _graded_honesty_rows(run)
    return [*lines, ""]


def _graded_honesty_rows(run: Path) -> list[str]:
    """Rows from the hand-graded perturbation and attribution sheets, once they are filled."""
    rows = []
    pert, att = run / "perturbation_sheet.csv", run / "attribution_sheet.csv"
    if pert.exists():
        p = pd.read_csv(pert)
        stance = p["stance_follows_data"].dropna().astype(str).str.lower()
        if len(stance):
            extra = p["extra_facts"].fillna("").astype(str).str.strip().str.lower()
            rows += [
                f"| Perturbation (graded): answer stance follows the data | "
                f"{int((stance == 'yes').sum())} of {len(stance)} |",
                f"| Perturbation (graded): answers adding facts beyond tool outputs | "
                f"{int(((extra != '') & (extra != 'none')).sum())} of {len(stance)} |",
            ]
    if att.exists():
        a = pd.read_csv(att)["reason_matches_driver"].dropna().astype(str).str.lower()
        if len(a):
            counts = ", ".join(f"{k} {int((a == k).sum())}" for k in ("yes", "partly", "no"))
            rows.append(
                f"| Attribution (graded): stated reason matches the top driver | "
                f"{counts} (n = {len(a)}) |"
            )
    return rows


def _figures(m: dict, out: Path) -> None:
    """Three figures: accuracy by system, NDCG by history tercile, popularity of recommendations."""
    out.mkdir(parents=True, exist_ok=True)
    systems = list(m["systems"])
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.5))
    for ax, metric in zip(axes, ("recall", "ndcg"), strict=True):
        values = [m["systems"][s][metric] for s in systems]
        ax.bar(
            systems,
            [v["mean"] for v in values],
            yerr=[[v["mean"] - v["lo"] for v in values], [v["hi"] - v["mean"] for v in values]],
            capsize=3,
            color="#4C78A8",
        )
        ax.set_title(f"{metric.upper()}@{m['k']} ({m['split']}, 95% CI)")
        ax.tick_params(axis="x", rotation=30)
    fig.tight_layout()
    fig.savefig(out / "accuracy_by_system.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.5))
    width = 0.8 / len(systems)
    for i, s in enumerate(systems):
        seg = m["systems"][s]["segments"]
        tiers = [t for t in ("small", "medium", "large") if t in seg]
        ax.bar(
            [j + i * width for j in range(len(tiers))],
            [seg[t]["ndcg"]["mean"] for t in tiers],
            width=width,
            label=s,
        )
    ax.set_xticks([j + 0.4 - width / 2 for j in range(3)], ["small", "medium", "large"])
    ax.set_title("NDCG by train-history tercile")
    ax.legend(fontsize=7, ncol=3)
    fig.tight_layout()
    fig.savefig(out / "ndcg_by_history_tercile.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.5))
    ax.bar(systems, [m["systems"][s]["pop_ratio"] for s in systems], color="#F58518")
    ax.axhline(1.0, color="grey", linestyle="--", linewidth=1)
    ax.set_title("Mean popularity of recommendations / of the user's history")
    ax.tick_params(axis="x", rotation=30)
    fig.tight_layout()
    fig.savefig(out / "popularity_ratio.png", dpi=150)
    plt.close(fig)


def _model_swap_table(cfg: Config, grading: Path, results: Path) -> list[str]:
    """Two LLMs on the same scenario turns, graded blind and paired (notes, gpt-5.1 trial).

    Reads `rubric_grades_blind_with_rationale.csv` (one row per model and turn) and the two
    agent runs it names; differences are other model minus the configured model, with a paired
    bootstrap CI over turns. Returns [] if the grades or either run are missing.
    """
    path = grading / "rubric_grades_blind_with_rationale.csv"
    if not path.exists():
        return []
    grades = pd.read_csv(path)
    run_of = grades.groupby("model")["run"].first().to_dict()
    base = cfg.agent.model
    others = [m for m in run_of if m != base]
    if (
        base not in run_of
        or len(others) != 1
        or not all((results / r / "metrics.json").exists() for r in run_of.values())
    ):
        return []
    other = others[0]
    m = {k: _load(results / r) for k, r in run_of.items()}
    lines = [
        f"## Model swap on val: {other} vs {base} — `{run_of[other]}` vs `{run_of[base]}`",
        "",
        "Same prompt, code and scenarios; rubric graded blind and paired "
        "(`eval/grading/rubric_grades_blind_with_rationale.csv`).",
        "",
        f"| Measure | {other} | {base} | Difference [95% CI] | Better / same / worse |",
        "|---|---|---|---|---|",
    ]
    for key in (
        "scenario_success",
        "verifier_first_pass_rate",
        "fallback_rate",
        "tool_chain_accuracy",
        "mean_tool_calls",
        "p50_latency_ms",
        "p95_latency_ms",
    ):
        lines.append(f"| {key} | {m[other][key]:.2f} | {m[base][key]:.2f} | - | - |")
    wide = grades.pivot_table(index=["scenario", "turn"], columns="model", values=RUBRIC_CRITERIA)
    rng = np.random.default_rng(cfg.seed)
    for c in RUBRIC_CRITERIA:
        a, b = wide[(c, other)].to_numpy(), wide[(c, base)].to_numpy()
        d = a - b
        ci = paired_bootstrap(a, b, cfg, rng)
        lines.append(
            f"| rubric {c} (0–2, {len(d)} turns) | {a.mean():.2f} | {b.mean():.2f} | "
            f"{ci['mean']:+.2f} [{ci['lo']:+.2f}, {ci['hi']:+.2f}] | "
            f"{int((d > 0).sum())} / {int((d == 0).sum())} / {int((d < 0).sum())} |"
        )
    lines += _blind_honesty_rows(grading, other, base)
    return [*lines, ""]


def _blind_honesty_rows(grading: Path, other: str, base: str) -> list[str]:
    """Blind-graded perturbation and attribution counts per model, if those files exist."""
    rows = []
    pert = grading / "perturbation_grades_blind_with_rationale.csv"
    att = grading / "attribution_grades_blind_with_rationale.csv"
    if pert.exists():
        p = pd.read_csv(pert)
        p["extra"] = p["extra_facts"].fillna("none").astype(str).str.strip().str.lower() != "none"
        stance, extra = {}, {}
        for model, g in p.groupby("model"):
            n = len(g)
            stance[model] = f"{int((g['stance_follows_data'].str.lower() == 'yes').sum())} of {n}"
            extra[model] = f"{int(g['extra'].sum())} of {n}"
        rows.append(
            f"| perturbation: stance follows the data | {stance[other]} | {stance[base]} | - | - |"
        )
        rows.append(
            f"| perturbation: adds facts beyond tools | {extra[other]} | {extra[base]} | - | - |"
        )
    if att.exists():
        a = pd.read_csv(att)
        counts = {}
        for model, g in a.groupby("model"):
            v = g["reason_matches_driver"].str.lower()
            counts[model] = " / ".join(str(int((v == k).sum())) for k in ("yes", "partly", "no"))
        rows.append(
            f"| attribution: yes / partly / no | {counts[other]} | {counts[base]} | - | - |"
        )
    return rows
